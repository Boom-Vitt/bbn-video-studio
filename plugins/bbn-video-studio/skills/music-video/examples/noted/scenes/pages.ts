import * as THREE from 'three'
import { C, F, canvasTexture, clamp, ease, el, lerp, pulse, rng, seg, slate } from '../kit'
import { animateMascot, mascot } from '../mascot'
import type { SceneDef } from '../types'

export default {
  theme: 'dark',
  type: { pos: 'bottom', size: 76, width: 1680 },
  create({ root, dom, cue, stage }) {
    stage.camera.position.y = 1.5
    stage.camera.lookAt(0, 0, 0)
    slate(dom, '02 / กะดึกของน้องสรุป', 'STRATEGY_2027_FINAL_V9.PDF')
    el('div', `position:absolute;left:120px;top:155px;font:500 16px ${F.mono};letter-spacing:.15em;color:${C.gray}`, dom, 'OVERNIGHT / AUTO-WRITING')
    const counter = el('div', `position:absolute;left:116px;top:200px;font:500 112px ${F.mono};letter-spacing:-.08em;color:${C.yellow}`, dom)
    el('div', `position:absolute;left:126px;top:342px;font:400 17px ${F.ui};color:${C.gray}`, dom, 'หน้า · โดยไม่มีใครสั่งหยุด')
    const clock = el('div', `position:absolute;right:120px;top:126px;font:500 42px ${F.mono};color:${C.white}`, dom)
    el('div', `position:absolute;right:120px;top:185px;font:400 14px ${F.mono};letter-spacing:.15em;color:${C.gray}`, dom, '23:47 → 06:00 / NIGHT SHIFT')
    const status = el('div', `position:absolute;right:120px;top:694px;font:500 17px ${F.mono};color:${C.yellow}`, dom)

    const props = new THREE.Group()
    props.rotation.y = -.16
    root.add(props)
    const deskMat = new THREE.MeshStandardMaterial({ color: C.ink3, roughness: .7, metalness: .3 })
    const desk = new THREE.Mesh(new THREE.BoxGeometry(6.7, .12, 1.8), deskMat)
    desk.position.set(-.15, -.74, 0); props.add(desk)
    for (const x of [-2.8, 2.5]) {
      const leg = new THREE.Mesh(new THREE.BoxGeometry(.09, .72, 1.35), deskMat)
      leg.position.set(x, -1.13, 0); props.add(leg)
    }
    const bot = mascot(C.yellow, .13)
    bot.group.position.set(-1.92, -.51, -.33)
    props.add(bot.group)
    const laptop = new THREE.Mesh(new THREE.BoxGeometry(1.08, .66, .06), deskMat)
    laptop.position.set(-1.23, -.12, .3); laptop.rotation.x = -.12; props.add(laptop)
    const screen = new THREE.Mesh(new THREE.PlaneGeometry(.94, .53), new THREE.MeshBasicMaterial({ color: '#303B56' }))
    screen.position.set(-1.23, -.12, .339); props.add(screen)
    const keyboard = new THREE.Mesh(new THREE.BoxGeometry(1.12, .035, .62), deskMat)
    keyboard.position.set(-1.23, -.65, .53); props.add(keyboard)
    const screenLines = Array.from({ length: 5 }, (_, i) => {
      const m = new THREE.Mesh(new THREE.PlaneGeometry(.55 - i % 2 * .17, .018), new THREE.MeshBasicMaterial({ color: i === 0 ? C.yellow : C.gray }))
      m.position.set(-1.32, .025 - i * .065, .345); props.add(m); return m
    })

    const paperTexture = canvasTexture(360, 500, g => {
      g.fillStyle = C.paper; g.fillRect(0, 0, 360, 500)
      g.fillStyle = C.ink; g.font = `500 20px ${F.mono}`; g.fillText('AI STRATEGY / 2027', 28, 45)
      g.fillStyle = C.red; g.fillRect(28, 67, 70, 4)
      g.fillStyle = '#A5A19A'
      for (let i = 0; i < 22; i++) g.fillRect(28, 99 + i * 15, i % 5 === 4 ? 180 : 298, 3)
      g.fillStyle = C.gray; g.font = `400 12px ${F.mono}`; g.fillText('GENERATED BY NONG SARUP', 28, 470)
    })
    const faceMat = new THREE.MeshBasicMaterial({ map: paperTexture, color: new THREE.Color(.5, .5, .5) })
    const edgeMat = new THREE.MeshBasicMaterial({ color: new THREE.Color(C.paper2).multiplyScalar(.45) })
    const geometry = new THREE.BoxGeometry(1.35, .012, 1.86)
    const random = rng(92)
    const pages = Array.from({ length: 92 }, (_, i) => {
      const mesh = new THREE.Mesh(geometry, [edgeMat, edgeMat, faceMat, edgeMat, edgeMat, edgeMat])
      props.add(mesh)
      return { mesh, x: 1.35 + (random() - .5) * .06, z: (random() - .5) * .06, turn: (random() - .5) * .045, i }
    })
    const moon = new THREE.Mesh(new THREE.CircleGeometry(.35, 48), new THREE.MeshBasicMaterial({ color: C.paper }))
    moon.position.set(3.28, 1.57, -1); root.add(moon)
    const moonCut = new THREE.Mesh(new THREE.CircleGeometry(.32, 48), new THREE.MeshBasicMaterial({ color: C.ink }))
    moonCut.position.set(3.42, 1.67, -.99); root.add(moonCut)
    const stars = Array.from({ length: 18 }, () => {
      const star = new THREE.Mesh(new THREE.PlaneGeometry(.012, .012), new THREE.MeshBasicMaterial({ color: C.gray }))
      star.position.set(random() * 7 - 2.7, random() * 1.3 + 1.35, -1.2)
      root.add(star); return star
    })

    return {
      update(f) {
        const line = f.lines[0]
        const p = seg(f.t, line?.start ?? cue.start, line ? lerp(line.start, line.end, .95) : cue.end)
        const progress = p * 98
        const count = Math.max(1, Math.min(92, Math.floor(progress)))
        counter.textContent = `${String(count).padStart(3, '0')}/092`
        const minutes = Math.round(1427 + p * 373) % 1440
        clock.textContent = `${String(Math.floor(minutes / 60)).padStart(2, '0')}:${String(minutes % 60).padStart(2, '0')}`
        status.textContent = p === 1 ? '✓ 092 PAGES / READY TO IGNORE' : '● กำลังเขียนแผน…'
        animateMascot(bot, f.beat, 1.4)
        bot.group.rotation.y = .12 + Math.sin(f.beat * Math.PI) * .045
        screenLines.forEach((m, i) => { m.scale.x = .6 + .4 * pulse(f.beat + i / 5) })
        pages.forEach(({ mesh, x, z, turn, i }) => {
          const fly = clamp((progress - i) / 6)
          mesh.visible = progress >= i
          const arrival = ease.out(fly)
          mesh.position.set(lerp(-.7, x, arrival), lerp(-.1, -.65 + i * .018, arrival) + Math.sin(fly * Math.PI) * 1.15, lerp(.2, z, arrival))
          mesh.rotation.set((1 - fly) * .8, turn + (1 - fly) * 1.3, Math.sin(fly * Math.PI) * -.35)
        })
        stars.forEach((m, i) => { m.scale.setScalar(.65 + .35 * Math.sin(f.beat * .4 + i)) })
      },
    }
  },
} satisfies SceneDef
